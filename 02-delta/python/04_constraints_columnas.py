# MAGIC %md
# MAGIC ## Columnas generadas
# MAGIC
# MAGIC Se calculan solas a partir de otras. Ventajas: no puedes olvidarlas ni meter un
# MAGIC valor incoherente, y el optimizador conoce la relación (puede podar por la
# MAGIC columna generada al filtrar por la base).
# MAGIC
# MAGIC Si en el `INSERT` das un valor, tiene que coincidir con el calculado o falla.

# COMMAND ----------

spark.sql("""
    CREATE OR REPLACE TABLE eventos (
      id   INT,
      ts   TIMESTAMP,
      dia  DATE GENERATED ALWAYS AS (CAST(ts AS DATE)),
      anio INT  GENERATED ALWAYS AS (YEAR(ts))
    )
""")

# Desde Python: el DataFrame NO lleva las columnas generadas
from pyspark.sql.functions import to_timestamp, col

df = spark.createDataFrame(
    [(1, "2026-01-15 10:30:00"), (2, "2026-02-20 18:45:00")], "id INT, ts STRING"
).select(col("id"), to_timestamp(col("ts")).alias("ts"))

df.write.mode("append").saveAsTable("eventos")
display(spark.table("eventos"))

# COMMAND ----------

# MAGIC %md
# MAGIC ## Columnas IDENTITY
# MAGIC
# MAGIC | Variante | Comportamiento |
# MAGIC |---|---|
# MAGIC | `GENERATED ALWAYS AS IDENTITY` | siempre la pone Delta; no puedes darle valor |
# MAGIC | `GENERATED BY DEFAULT AS IDENTITY` | la pone Delta salvo que tú des uno |
# MAGIC
# MAGIC Los valores son **únicos y crecientes, pero no consecutivos**: cada escritor
# MAGIC reserva un bloque y quedan huecos. No sirven para contar filas.

# COMMAND ----------

spark.sql("""
    CREATE OR REPLACE TABLE dim_producto (
      sk     BIGINT GENERATED ALWAYS AS IDENTITY,
      nombre STRING
    )
""")

spark.createDataFrame([("teclado",), ("raton",), ("monitor",)], "nombre STRING") \
    .write.mode("append").saveAsTable("dim_producto")

display(spark.table("dim_producto"))

# COMMAND ----------

spark.sql("""
    CREATE OR REPLACE TABLE dim_producto_def (
      sk     BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 10),
      nombre STRING
    )
""")

spark.sql("INSERT INTO dim_producto_def (nombre) VALUES ('teclado')")
spark.sql("INSERT INTO dim_producto_def (sk, nombre) VALUES (999, 'importado')")
spark.sql("INSERT INTO dim_producto_def (nombre) VALUES ('raton')")

display(spark.table("dim_producto_def").orderBy("sk"))

# COMMAND ----------

# MAGIC %md
# MAGIC ## PK y FK: informativas
# MAGIC
# MAGIC Requieren `NOT NULL`. Se marcan `RELY` si quieres que el optimizador se fíe. Pero
# MAGIC nadie te impide insertar duplicados ni huérfanos.

# COMMAND ----------

spark.sql("""
    CREATE OR REPLACE TABLE dim_pais (
      codigo STRING NOT NULL,
      nombre STRING,
      CONSTRAINT pk_pais PRIMARY KEY (codigo) RELY
    )
""")

spark.createDataFrame(
    [("ES", "España"), ("PT", "Portugal"), ("ES", "España duplicada")],
    "codigo STRING, nombre STRING",
).write.mode("append").saveAsTable("dim_pais")

# Se ha insertado el duplicado: la PK no se aplica
display(spark.table("dim_pais").orderBy("codigo"))

# COMMAND ----------

# MAGIC %md
# MAGIC ## Si necesitas unicidad de verdad
# MAGIC
# MAGIC No hay constraint que te la dé. Las dos vías reales:
# MAGIC
# MAGIC 1. **`MERGE` sobre la clave** en vez de `append` (ver notebook 01).
# MAGIC 2. Un **`CHECK` no vale** para esto; lo que sí sirve es una comprobación de
# MAGIC    calidad que falle el job si aparecen duplicados.

# COMMAND ----------

dups = spark.sql("""
    SELECT codigo, count(*) AS n
    FROM dim_pais
    GROUP BY codigo
    HAVING count(*) > 1
""")

if dups.count() > 0:
    display(dups)
    print("Hay duplicados. En un job real esto sería un raise.")
