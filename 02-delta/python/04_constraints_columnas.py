# MAGIC %md
# MAGIC # 04 · Constraints y columnas especiales (Python)
# MAGIC
# MAGIC Estas cosas **se definen en DDL**, no hay API de DataFrames para ellas. Así que
# MAGIC este notebook usa `spark.sql(...)` para crearlas y Python para probarlas.
# MAGIC
# MAGIC | Constraint | ¿Se aplica de verdad? |
# MAGIC |---|---|
# MAGIC | `NOT NULL` | **sí** |
# MAGIC | `CHECK` | **sí** |
# MAGIC | `PRIMARY KEY` | **no**, informativa |
# MAGIC | `FOREIGN KEY` | **no**, informativa |
# MAGIC
# MAGIC Delta **no** garantiza unicidad de PK. Si no quieres duplicados, es tu trabajo.

# COMMAND ----------

CATALOGO, ESQUEMA = "main", "demo_delta_py"
spark.sql(f"CREATE SCHEMA IF NOT EXISTS {CATALOGO}.{ESQUEMA}")
spark.sql(f"USE CATALOG {CATALOGO}")
spark.sql(f"USE SCHEMA {ESQUEMA}")

# COMMAND ----------

spark.sql("""
    CREATE OR REPLACE TABLE pedidos (
      id       INT    NOT NULL,
      cliente  STRING NOT NULL,
      importe  DOUBLE,
      estado   STRING
    )
""")

spark.sql("ALTER TABLE pedidos ADD CONSTRAINT importe_positivo CHECK (importe > 0)")
spark.sql("""
    ALTER TABLE pedidos ADD CONSTRAINT estado_valido
      CHECK (estado IN ('nuevo','enviado','entregado','cancelado'))
""")

# COMMAND ----------

# MAGIC %md
# MAGIC Al añadir un `CHECK` a una tabla con datos, Databricks **valida lo que ya está**.
# MAGIC Si alguna fila lo incumple, el `ALTER` falla.

# COMMAND ----------

ok = spark.createDataFrame(
    [(1, "Ana", 100.0, "nuevo"), (2, "Bruno", 20.0, "enviado")],
    "id INT, cliente STRING, importe DOUBLE, estado STRING",
)
ok.write.mode("append").saveAsTable("pedidos")
display(spark.table("pedidos"))

# COMMAND ----------

def probar(df, etiqueta):
    """Intenta escribir y cuenta qué constraint la ha parado."""
    try:
        df.write.mode("append").saveAsTable("pedidos")
        print(f"{etiqueta}: escrito")
    except Exception as e:
        print(f"{etiqueta}: RECHAZADO -> {str(e)[:180]}")


probar(spark.createDataFrame([(3, None, 10.0, "nuevo")],
       "id INT, cliente STRING, importe DOUBLE, estado STRING"), "cliente NULL")

probar(spark.createDataFrame([(4, "Carla", -5.0, "nuevo")],
       "id INT, cliente STRING, importe DOUBLE, estado STRING"), "importe negativo")

probar(spark.createDataFrame([(5, "Diego", 10.0, "inventado")],
       "id INT, cliente STRING, importe DOUBLE, estado STRING"), "estado inválido")

# COMMAND ----------

# Los CHECK viven en las propiedades de la tabla
display(spark.sql("SHOW TBLPROPERTIES pedidos"))

# COMMAND ----------

spark.sql("ALTER TABLE pedidos DROP CONSTRAINT estado_valido")

