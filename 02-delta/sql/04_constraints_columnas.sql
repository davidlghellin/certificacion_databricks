-- MAGIC %md
-- MAGIC ## CHECK
-- MAGIC
-- MAGIC Al añadir un `CHECK` a una tabla con datos, Databricks **valida las filas que
-- MAGIC ya están**. Si alguna lo incumple, el `ALTER` falla.

-- COMMAND ----------

ALTER TABLE pedidos ADD CONSTRAINT importe_positivo CHECK (importe > 0);

ALTER TABLE pedidos ADD CONSTRAINT estado_valido
