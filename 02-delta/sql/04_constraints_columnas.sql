-- MAGIC # 04 · Constraints y columnas especiales
-- MAGIC
-- MAGIC Lo importante aquí es **cuáles se aplican de verdad y cuáles no**:
-- MAGIC
-- MAGIC | Constraint | ¿Se aplica? |
-- MAGIC |---|---|
-- MAGIC | `NOT NULL` | **Sí**, rechaza la escritura |
-- MAGIC | `CHECK` | **Sí**, rechaza la escritura |
-- MAGIC | `PRIMARY KEY` | **No**. Es informativa (para el optimizador y la doc) |
-- MAGIC | `FOREIGN KEY` | **No**. Informativa |
-- MAGIC
-- MAGIC O sea: Delta **no** garantiza unicidad de la PK. Si necesitas que no haya
-- MAGIC duplicados, es cosa tuya (un `MERGE` deduplicado, ver notebook 01).

-- COMMAND ----------

